-- ============================================================
-- 1. PRODUCT CATEGORY ENUM
-- ============================================================

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_type
        WHERE typname = 'product_category'
    ) THEN
        CREATE TYPE product_category AS ENUM (
            'Coffee',
            'Non-Coffee',
            'Refreshers'
        );
    END IF;
END
$$;


-- ============================================================
-- 2. PRODUCT TABLE
-- ============================================================

CREATE TABLE IF NOT EXISTS Product (
    ProductID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ProductName VARCHAR(45) NOT NULL,
    Category product_category NOT NULL,
    SellingPrice NUMERIC(10,2) NOT NULL,
    ProductCost NUMERIC(10,2) NOT NULL DEFAULT 0,
    PackagingCost NUMERIC(10,2) DEFAULT 0,
    ProductImage TEXT,
    IsAvailable BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT chk_product_selling_price
        CHECK (SellingPrice >= 0),

    CONSTRAINT chk_product_cost
        CHECK (ProductCost >= 0),

    CONSTRAINT chk_packaging_cost
        CHECK (PackagingCost >= 0)
);


-- ============================================================
-- 3. USER TABLE
-- ============================================================

CREATE TABLE IF NOT EXISTS "User" (
    UserID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FullName VARCHAR(45) NOT NULL,
    Username VARCHAR(45) NOT NULL UNIQUE,
    Password VARCHAR(255) NOT NULL,
    Role VARCHAR(45) NOT NULL,
    IsActive BOOLEAN NOT NULL DEFAULT TRUE
);


-- ============================================================
-- 4. INVENTORY TABLE
-- ============================================================

CREATE TABLE IF NOT EXISTS Inventory (
    InventoryID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ProductID INT NOT NULL,
    InventoryName VARCHAR(45) NOT NULL,
    Unit VARCHAR(45) NOT NULL,
    UnitCost NUMERIC(10,2) NOT NULL DEFAULT 0,
    BeginningStock NUMERIC(10,2) NOT NULL DEFAULT 0,
    CurrentStock NUMERIC(10,2) NOT NULL DEFAULT 0,
    ReorderLevel NUMERIC(10,2) NOT NULL DEFAULT 0,
    StockStatus VARCHAR(45),
    Barcode VARCHAR(45),
    QtyUsed NUMERIC(10,2) DEFAULT 0,
    BatchNo VARCHAR(45),

    CONSTRAINT fk_inventory_product
        FOREIGN KEY (ProductID)
        REFERENCES Product(ProductID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_inventory_unitcost
        CHECK (UnitCost >= 0),

    CONSTRAINT chk_inventory_stock
        CHECK (CurrentStock >= 0),

    CONSTRAINT chk_inventory_reorder
        CHECK (ReorderLevel >= 0)
);


-- ============================================================
-- 5. ORDERS TABLE
-- ============================================================

CREATE TABLE IF NOT EXISTS Orders (
    OrderID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    UserID INT NOT NULL,
    ProductID INT NOT NULL,
    OrderNumber VARCHAR(45) NOT NULL UNIQUE,
    CustomerName VARCHAR(45),
    Quantity INT NOT NULL,
    UnitPrice NUMERIC(10,2) NOT NULL,
    Customization VARCHAR(45),
    ServiceCharge NUMERIC(10,2) DEFAULT 0,
    TotalAmount NUMERIC(10,2) NOT NULL,
    PaymentMethod VARCHAR(45),
    AmountTendered NUMERIC(10,2) DEFAULT 0,
    OrderDateTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    OrderStatus VARCHAR(45) NOT NULL DEFAULT 'Completed',

    CONSTRAINT fk_orders_user
        FOREIGN KEY (UserID)
        REFERENCES "User"(UserID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_orders_product
        FOREIGN KEY (ProductID)
        REFERENCES Product(ProductID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_order_quantity
        CHECK (Quantity > 0),

    CONSTRAINT chk_order_unitprice
        CHECK (UnitPrice >= 0),

    CONSTRAINT chk_order_servicecharge
        CHECK (ServiceCharge >= 0),

    CONSTRAINT chk_order_total
        CHECK (TotalAmount >= 0),

    CONSTRAINT chk_order_tendered
        CHECK (AmountTendered >= 0)
);


-- ============================================================
-- 6. EXPENSE TABLE
-- ============================================================

CREATE TABLE IF NOT EXISTS Expense (
    ExpenseID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    UserID INT NOT NULL,
    ExpenseType VARCHAR(45) NOT NULL,
    Description TEXT,
    Amount NUMERIC(10,2) NOT NULL,
    ExpenseDate DATE NOT NULL DEFAULT CURRENT_DATE,

    CONSTRAINT fk_expense_user
        FOREIGN KEY (UserID)
        REFERENCES "User"(UserID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_expense_amount
        CHECK (Amount >= 0)
);


-- ============================================================
-- 7. REFUND TABLE
-- ============================================================

CREATE TABLE IF NOT EXISTS Refund (
    RefundID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OrderID INT NOT NULL,
    ApprovedBy INT,
    RefundAmount NUMERIC(10,2) NOT NULL,
    Reason VARCHAR(45),
    RefundDate TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ItemReturned BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT fk_refund_order
        FOREIGN KEY (OrderID)
        REFERENCES Orders(OrderID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_refund_approver
        FOREIGN KEY (ApprovedBy)
        REFERENCES "User"(UserID)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT chk_refund_amount
        CHECK (RefundAmount >= 0)
);


