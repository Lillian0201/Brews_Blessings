-- 9. DAILY SALES REPORT
-- Prevents duplicate sales totals caused by multiple refunds
-- ============================================================

CREATE OR REPLACE VIEW vw_sales_report AS

WITH refund_summary AS (
    SELECT
        OrderID,
        SUM(RefundAmount) AS TotalRefunds
    FROM Refund
    GROUP BY OrderID
)

SELECT
    DATE(o.OrderDateTime) AS SalesDate,
    COUNT(o.OrderID) AS TotalOrders,
    SUM(o.Quantity) AS TotalItemsSold,
    SUM(o.TotalAmount) AS GrossSales,
    COALESCE(SUM(rs.TotalRefunds), 0) AS TotalRefunds,

    SUM(o.TotalAmount)
        - COALESCE(SUM(rs.TotalRefunds), 0)
        AS NetSales,

    SUM(
        o.Quantity * (o.UnitPrice - p.ProductCost)
    ) AS GrossProfit,

    SUM(
        o.Quantity * (o.UnitPrice - p.ProductCost)
    ) - COALESCE(SUM(rs.TotalRefunds), 0)
        AS NetProfit

FROM Orders o

JOIN Product p
    ON o.ProductID = p.ProductID

LEFT JOIN refund_summary rs
    ON o.OrderID = rs.OrderID

WHERE o.OrderStatus = 'Completed'

GROUP BY DATE(o.OrderDateTime);


