-- 10. OVERALL SALES SUMMARY
-- ============================================================

CREATE OR REPLACE VIEW vw_overall_sales AS

WITH refund_summary AS (
    SELECT
        OrderID,
        SUM(RefundAmount) AS TotalRefunds
    FROM Refund
    GROUP BY OrderID
)

SELECT
    COUNT(o.OrderID) AS TotalOrders,
    COALESCE(SUM(o.Quantity), 0) AS TotalItemsSold,
    COALESCE(SUM(o.TotalAmount), 0) AS GrossSales,
    COALESCE(SUM(rs.TotalRefunds), 0) AS TotalRefunds,

    COALESCE(SUM(o.TotalAmount), 0)
        - COALESCE(SUM(rs.TotalRefunds), 0)
        AS NetSales,

    COALESCE(
        SUM(o.Quantity * (o.UnitPrice - p.ProductCost)),
        0
    ) AS GrossProfit,

    COALESCE(
        SUM(o.Quantity * (o.UnitPrice - p.ProductCost)),
        0
    ) - COALESCE(SUM(rs.TotalRefunds), 0)
        AS NetProfit

FROM Orders o

JOIN Product p
    ON o.ProductID = p.ProductID

LEFT JOIN refund_summary rs
    ON o.OrderID = rs.OrderID

WHERE o.OrderStatus = 'Completed';


