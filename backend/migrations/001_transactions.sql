BEGIN;

-- ------------------------------------------------------------
-- 1. ORDERS: discount + void tracking, allow multi-item orders
-- ------------------------------------------------------------
ALTER TABLE Orders ADD COLUMN IF NOT EXISTS DiscountAmount NUMERIC(10,2) NOT NULL DEFAULT 0;
ALTER TABLE Orders ADD COLUMN IF NOT EXISTS VoidReason VARCHAR(255);
ALTER TABLE Orders ADD COLUMN IF NOT EXISTS VoidedBy INT
    REFERENCES "User"(UserID) ON UPDATE CASCADE ON DELETE SET NULL;
ALTER TABLE Orders ADD COLUMN IF NOT EXISTS VoidedAt TIMESTAMP;

-- Items now live in OrderItem, so these legacy single-item columns become optional.
ALTER TABLE Orders ALTER COLUMN ProductID DROP NOT NULL;
ALTER TABLE Orders ALTER COLUMN Quantity  DROP NOT NULL;
ALTER TABLE Orders ALTER COLUMN UnitPrice DROP NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_order_discount') THEN
        ALTER TABLE Orders ADD CONSTRAINT chk_order_discount CHECK (DiscountAmount >= 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_order_status') THEN
        ALTER TABLE Orders ADD CONSTRAINT chk_order_status
            CHECK (OrderStatus IN ('Pending', 'Completed', 'Cancelled', 'Voided', 'Refunded'));
    END IF;
END
$$;

-- ------------------------------------------------------------
-- 2. ORDERITEM: one row per drink in an order
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS OrderItem (
    OrderItemID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OrderID INT NOT NULL,
    ProductID INT,
    ItemName VARCHAR(100) NOT NULL,
    Quantity INT NOT NULL,
    UnitPrice NUMERIC(10,2) NOT NULL,
    Customization TEXT,

    CONSTRAINT fk_orderitem_order
        FOREIGN KEY (OrderID) REFERENCES Orders(OrderID)
        ON UPDATE CASCADE ON DELETE CASCADE,

    CONSTRAINT fk_orderitem_product
        FOREIGN KEY (ProductID) REFERENCES Product(ProductID)
        ON UPDATE CASCADE ON DELETE RESTRICT,

    CONSTRAINT chk_orderitem_qty   CHECK (Quantity > 0),
    CONSTRAINT chk_orderitem_price CHECK (UnitPrice >= 0)
);

CREATE INDEX IF NOT EXISTS idx_orderitem_order   ON OrderItem(OrderID);
CREATE INDEX IF NOT EXISTS idx_orderitem_product ON OrderItem(ProductID);

-- ------------------------------------------------------------
-- 3. REFUND: request -> approve/reject flow
-- ------------------------------------------------------------
-- Rows that already exist were approved refunds, so they start as 'Approved'.
ALTER TABLE Refund ADD COLUMN IF NOT EXISTS Status VARCHAR(20) NOT NULL DEFAULT 'Approved';
ALTER TABLE Refund ALTER COLUMN Status SET DEFAULT 'Pending';
ALTER TABLE Refund ADD COLUMN IF NOT EXISTS RequestedBy INT
    REFERENCES "User"(UserID) ON UPDATE CASCADE ON DELETE SET NULL;
ALTER TABLE Refund ADD COLUMN IF NOT EXISTS RequestedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE Refund ADD COLUMN IF NOT EXISTS ApprovedAt TIMESTAMP;
ALTER TABLE Refund ADD COLUMN IF NOT EXISTS ItemName VARCHAR(100);
ALTER TABLE Refund ALTER COLUMN Reason TYPE VARCHAR(255);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_refund_status') THEN
        ALTER TABLE Refund ADD CONSTRAINT chk_refund_status
            CHECK (Status IN ('Pending', 'Approved', 'Rejected'));
    END IF;
END
$$;

-- At most one pending refund request per order.
CREATE UNIQUE INDEX IF NOT EXISTS uq_refund_one_pending
    ON Refund(OrderID) WHERE Status = 'Pending';

CREATE INDEX IF NOT EXISTS idx_refund_status ON Refund(Status);

-- ------------------------------------------------------------
-- 4. AUDITLOG: who did what (used by void / refund actions)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS AuditLog (
    AuditID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    UserID INT,
    Action VARCHAR(255) NOT NULL,
    TableName VARCHAR(45) NOT NULL,
    RecordID INT,
    CreatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_auditlog_user
        FOREIGN KEY (UserID) REFERENCES "User"(UserID)
        ON UPDATE CASCADE ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_auditlog_created ON AuditLog(CreatedAt);

-- ------------------------------------------------------------
-- 5. SALES VIEWS: rebuilt for the new tables
--    - sales = Completed + Refunded orders (Voided/Pending/Cancelled excluded)
--    - only APPROVED refunds are subtracted
--    - items and profit come from OrderItem (no row duplication)
--    - discounts are subtracted from profit
-- ------------------------------------------------------------
DROP VIEW IF EXISTS vw_sales_report;
DROP VIEW IF EXISTS vw_overall_sales;

CREATE VIEW vw_sales_report AS
WITH refund_summary AS (
    SELECT OrderID, SUM(RefundAmount) AS TotalRefunds
    FROM Refund
    WHERE Status = 'Approved'
    GROUP BY OrderID
),
item_summary AS (
    SELECT
        oi.OrderID,
        SUM(oi.Quantity) AS ItemsSold,
        SUM(oi.Quantity * (oi.UnitPrice - COALESCE(p.ProductCost, 0))) AS ItemProfit
    FROM OrderItem oi
    LEFT JOIN Product p ON p.ProductID = oi.ProductID
    GROUP BY oi.OrderID
)
SELECT
    DATE(o.OrderDateTime) AS SalesDate,
    COUNT(o.OrderID) AS TotalOrders,
    COALESCE(SUM(i.ItemsSold), 0) AS TotalItemsSold,
    SUM(o.TotalAmount) AS GrossSales,
    COALESCE(SUM(rs.TotalRefunds), 0) AS TotalRefunds,
    SUM(o.TotalAmount) - COALESCE(SUM(rs.TotalRefunds), 0) AS NetSales,
    COALESCE(SUM(i.ItemProfit), 0) - SUM(o.DiscountAmount) AS GrossProfit,
    COALESCE(SUM(i.ItemProfit), 0) - SUM(o.DiscountAmount)
        - COALESCE(SUM(rs.TotalRefunds), 0) AS NetProfit
FROM Orders o
LEFT JOIN item_summary i    ON i.OrderID = o.OrderID
LEFT JOIN refund_summary rs ON rs.OrderID = o.OrderID
WHERE o.OrderStatus IN ('Completed', 'Refunded')
GROUP BY DATE(o.OrderDateTime);

CREATE VIEW vw_overall_sales AS
WITH refund_summary AS (
    SELECT OrderID, SUM(RefundAmount) AS TotalRefunds
    FROM Refund
    WHERE Status = 'Approved'
    GROUP BY OrderID
),
item_summary AS (
    SELECT
        oi.OrderID,
        SUM(oi.Quantity) AS ItemsSold,
        SUM(oi.Quantity * (oi.UnitPrice - COALESCE(p.ProductCost, 0))) AS ItemProfit
    FROM OrderItem oi
    LEFT JOIN Product p ON p.ProductID = oi.ProductID
    GROUP BY oi.OrderID
)
SELECT
    COUNT(o.OrderID) AS TotalOrders,
    COALESCE(SUM(i.ItemsSold), 0) AS TotalItemsSold,
    COALESCE(SUM(o.TotalAmount), 0) AS GrossSales,
    COALESCE(SUM(rs.TotalRefunds), 0) AS TotalRefunds,
    COALESCE(SUM(o.TotalAmount), 0) - COALESCE(SUM(rs.TotalRefunds), 0) AS NetSales,
    COALESCE(SUM(i.ItemProfit), 0) - COALESCE(SUM(o.DiscountAmount), 0) AS GrossProfit,
    COALESCE(SUM(i.ItemProfit), 0) - COALESCE(SUM(o.DiscountAmount), 0)
        - COALESCE(SUM(rs.TotalRefunds), 0) AS NetProfit
FROM Orders o
LEFT JOIN item_summary i    ON i.OrderID = o.OrderID
LEFT JOIN refund_summary rs ON rs.OrderID = o.OrderID
WHERE o.OrderStatus IN ('Completed', 'Refunded');

COMMIT;
