BEGIN;

CREATE TABLE IF NOT EXISTS ingredient (
    ingredientid   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(60) NOT NULL UNIQUE,
    barcode        VARCHAR(45) UNIQUE,
    unit           VARCHAR(20) NOT NULL,
    unitcost       NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (unitcost >= 0),
    beginningstock NUMERIC(10,3) NOT NULL DEFAULT 0 CHECK (beginningstock >= 0),
    reorderlevel   NUMERIC(10,3) NOT NULL DEFAULT 0 CHECK (reorderlevel >= 0),
    isactive       BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS stockbatch (
    batchid       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingredientid  INT NOT NULL REFERENCES ingredient(ingredientid) ON DELETE RESTRICT,
    batchno       VARCHAR(45) NOT NULL,
    qtyreceived   NUMERIC(10,3) NOT NULL CHECK (qtyreceived > 0),
    qtyremaining  NUMERIC(10,3) NOT NULL CHECK (qtyremaining >= 0),
    receiveddate  DATE NOT NULL DEFAULT CURRENT_DATE
);
CREATE INDEX IF NOT EXISTS idx_stockbatch_fifo ON stockbatch(ingredientid, receiveddate, batchid);

CREATE TABLE IF NOT EXISTS stockmovement (
    movementid    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingredientid  INT NOT NULL REFERENCES ingredient(ingredientid) ON DELETE RESTRICT,
    batchid       INT REFERENCES stockbatch(batchid) ON DELETE SET NULL,
    orderid       INT REFERENCES orders(orderid) ON DELETE SET NULL,
    userid        INT REFERENCES "User"(userid) ON DELETE SET NULL,
    movementtype  VARCHAR(20) NOT NULL
                  CHECK (movementtype IN ('Stock-In', 'Stock-Out', 'Restore', 'Waste')),
    quantity      NUMERIC(10,3) NOT NULL CHECK (quantity > 0),
    note          TEXT,
    createdat     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_stockmovement_order   ON stockmovement(orderid);
CREATE INDEX IF NOT EXISTS idx_stockmovement_created ON stockmovement(createdat);

CREATE TABLE IF NOT EXISTS recipe (
    recipeid      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    productid     INT NOT NULL REFERENCES product(productid) ON DELETE CASCADE,
    ingredientid  INT NOT NULL REFERENCES ingredient(ingredientid) ON DELETE RESTRICT,
    qtyused       NUMERIC(10,3) NOT NULL CHECK (qtyused > 0),
    UNIQUE (productid, ingredientid)
);

ALTER TABLE orders ADD COLUMN IF NOT EXISTS cancelreason VARCHAR(255);

